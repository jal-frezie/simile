int InstanceOfModel::loses (double prob, int phase) {
  /* kills_per_step was intended to make sure that for R-K the same proportion 
     get killed in four passes as in a single pass for Euler. As of 5.7 we make
     sure the loss process only happens once per time step. */
//  int kills_per_step;
  if (prob<=0 || ts[0]<0) {
    return 0;
  } else if (prob>=1) {
    return 1;
  } else {
//    kills_per_step=glob_element(ts,0)?4:1;
//    return ame_rand(0,1)>pow(1-prob,glob_element(dts,phase)/kills_per_step);
    return ame_rand(0,1)>pow(1-prob,dts[phase]);
  }
}

double InstanceOfModel::stage_incr (double comp, diffs *extras, int step, 
				    double v, int useLims, 
				    double min, double max, int graphId) {
  double dv, span, result, errMagn;
  /*
In this version, the three intermediate increments are kept in t1-t3 while
building the full R-K increment. After this is complete they are assigned:
t1 = initial rate of change (used when redoing step with different dt)
t2 = last increment (used to undo step)
t3 = estimate of next initial increment
  */
  if (ts[0]<0) {
    dv = extras->t1*dts[step];
  } else {
    dv = v*dts[step];
  }
  switch (int(ts[0])) {
  case 0: // Euler
    extras->t1 = v;
    extras->t2 = dv;
    return (extras->t3 = dv);
  case 1: // these 4 are R-K
    return (extras->t1 = dv)/2;
  case 2:
    return ((extras->t2 = dv) - extras->t1)/2;
  case 3:
    return (extras->t3 = dv) - extras->t2/2;
  case 4:
    extras->t2 = (extras->t1 + 2*extras->t2 + 2*extras->t3 + dv)/6;
    result = extras->t2 - extras->t3;
    extras->t3 = (-extras->t1 + 2*extras->t3 + 2*dv)/3;
    extras->t1 = extras->t1/dts[step];
    return result;
  case 5: case 6:
    if ((useLims & 1) && comp<min && comp-extras->t2>=min) {
      userStop.targetId = -graphId;
      report_context();
    } else if ((useLims & 2) && comp>max && comp-extras->t2<=max) {
      userStop.targetId = graphId;
      report_context();
    }
   return 0;
  case -1: // undoes previous change Euler
    result = extras->t2;
    extras->t3 = dv;
    return (extras->t2 = dv)-result;
  case -2: // undoes previous change R-K
    return (extras->t1 = dv)/2 - extras->t2;
  case 10: case 11: // does not change compartment, just checks for errors
  default: // stops compiler warning possible null return
    if (useLims==3)
      span = max - min;
    else
      span = 100;
    errMagn = fabs(dv-extras->t3)*100/span;
    if (errMagn>adapt_maxerr) {
      userStop.targetId = graphId;
      adapt_maxerr = errMagn;
    }
    return 0;
  };
};

void InstanceOfModel::report_context() {
  int mdCount = 0, n, *m;
  ctxCount = 0;
  while (loopIndexPtrs[mdCount]) {
    if (loopIndexCounts[mdCount] == -1) {
      ctxSaved[ctxCount++] = *(int*)(loopIndexPtrs[mdCount]);
    } else {
      for (n=0; n<loopIndexCounts[mdCount]; ++n) {
	m = &n;
	m = (int*)(*(submodeltype**)(loopIndexPtrs[mdCount]))->get_pointer(2, &m);
	ctxSaved[ctxCount++] = *m;
      }
    }
    ++mdCount;
  }
  //  compare_instance_status(itIsThus, itIsThus, -ctxCount);
  //  now done at end of step
}

BOOLEAN RealPhase(int phase) {
  return phase==5 || phase==6 || phase==9;
}

#define   CHECK_LOWER   1
#define   CHECK_UPPER   2
#define   LIMIT_FUZZ    1e-12
// allow use of predictions with small (e.g., rounding-only) errors
int InstanceOfModel::check_limit (double trigger, double lower, double upper,
				  int action, int graphId, 
				  int step, diffs* extras) {
  double old, to_limit, rate, prediction;
  int out, heading_out, phase = int(ts[0]);
  switch (phase) {
  case 0: case 1: // resetting model, do not use saved data
    extras->t1 = trigger; // for prediction next step
    // go = (to_limit < 0); events on init = nothing but trouble
    break;
  case 2: // next 3 are R-K substeps
    extras->t2 = trigger;
    break;
  case 3:
    extras->t2 = (extras->t2+trigger)/2;
    break;
  case 5: // setting model rates for real -- euler
  case 6: // setting model rates for real -- R-K
  case 9: // setting model rates for real on reset -- no integration
  case 10: // error checking -- euler
  case 11: // error checking -- R-K
    heading_out = out = 0;
    if (phase==9) {
      old = trigger; // no heading or rate
      extras->t3 = 0; // ignore previous activation state
    } else
      old = extras->t1;
    if (action & CHECK_LOWER) {
      if (trigger<old) {
	heading_out = -1;
	to_limit = trigger-lower;
	rate = old-trigger;
      }
      if (trigger<lower+LIMIT_FUZZ)
	out = -1;
    }
    if (action & CHECK_UPPER) {
      if (trigger>old) {
	heading_out = 1;
	to_limit = upper-trigger;
	rate = trigger-old;
      }
      if (trigger>=upper-LIMIT_FUZZ)
	out = 1;
    }

    /* ok...if for_real, I need to update the last 'out' value and
       return the new value if it has changed, ot zero otherwise. If
       heading out, but not already fired (including this pass) I need
       to make a prediction (to be treated as an overshoot if out).
    */
    
    if (RealPhase(phase)) {
      extras->t1 = trigger; // for prediction next step
      if (out) {
	if (out != extras->t3) { 
	  userStop.targetId = graphId; // for pause-on-event reporting
	  flag_derived_event(graphId, out);
	  report_context();
	  extras->t3 = out;
	  return out; // cannot return result of above assignment
	  // because some compilers then complain about type conversion
	}
      } else
	extras->t3 = 0;
    }
    if (heading_out && extras->t3 != heading_out) { 
      // make prediction for this event
      if (phase==6 || phase==11) { // ok approximate to quadratic
	// (yes I know should be 4th-order poly but have you seen the formula!)
	// printf("old %f mid %f new %f\n", old, extras->t2, trigger);
	double a,b,det;
	a=-heading_out*2*(trigger-2*extras->t2+old)/pow(dts[step],2);
	if (a==0) // it is linear
	  prediction = ts[step] + dts[step]*to_limit/rate;
	else {
	  b=-heading_out*(3*trigger-4*extras->t2+old)/dts[step];

	  // that is the eqn for the curve. Determinant:
	  det = pow(b,2)-4*a*to_limit;
	  if (det<=0) return 0; // no misses or grazes
	  det = pow(det,0.5);
	  // printf("a %f b %f c %f det %f\n", a, b, to_limit, det);
	  if (to_limit*dts[step]>0) // inside limit XOR going backwards
	    prediction = ts[step] + (-b - det)/(2*a);
	  else // take later root
	    prediction = ts[step] + (-b + det)/(2*a);
	}
      } else // phase is 5 or 10, do linear extrap
	prediction = ts[step] + dts[step]*to_limit/rate;

      if (prediction<event_predict)
	event_predict = prediction;
    }
  }
  return 0;
}

template <class modeldata> 
modeldata InstanceOfModel::retract_from_pipe(delay<modeldata>* extras,
					     int graphId) {
  int phase = int(ts[0]);
  double time = ts[phasecount];
  BOOLEAN for_real = RealPhase(phase);
  modeldata ret;

  if (dts[0]>0) {
    ret = extras->retract(time, for_real);
    if (ret && for_real) {
      report_context();
      userStop.targetId = graphId;
      flag_derived_event(graphId, ret);
    }
    return ret;
  }
  else
    extras->empty();
  return 0;
}

template <class modeldata> 
void InstanceOfModel::insert_to_pipe(delay<modeldata>* extras, 
					  double wait, 
					  modeldata payload) {
  int phase = int(ts[0]);
  double time = ts[phasecount];

  extras->insert(time+wait, RealPhase(phase)?payload:0, &event_predict);
}

template <class modeldata>
modeldata InstanceOfModel::flag_derived_event(int graphId,
					      modeldata magnitude) {
  int count;
  if (!magnitude) return 0;
  for (count=activeEvtCount-1;count>=0;--count) {
    if (activeEvtIds[count] == graphId) { // element of array already active
      activeEvtSums[count] += magnitude;
      break;
    }
  }
  if (count == -1) { // new array
    activeEvtIds[activeEvtCount] = graphId;
    activeEvtSums[activeEvtCount++] = magnitude;
  }
  return magnitude;
}

